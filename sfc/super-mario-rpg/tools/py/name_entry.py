"""Data for the jamo name-entry screen (src/name_entry.asm).

Name characters, as stored in the 8-byte name buffer:
  $20-$FF       a menu-font code (old saves use only these)
  $01-$0A, l    name glyph n = (p - 1) * 256 + l, drawn from the 1bpp set below
Name glyphs: n < 51 are the compatibility jamo U+3131-U+3163, n = 51 + k is the
k-th KS X 1001 syllable in code-point order. Syllables the menu font has are
always stored as their 1-byte code, so a name only uses glyph n when it must.

The runtime builds syllables as (cho, jung, jong) with the Unicode indices and
looks s = (cho * 21 + jung) * 28 + jong up in NeKsSyl.
"""
import sys

JAMO = [chr(c) for c in range(0x3131, 0x3164)]
CHO = 'ㄱㄲㄴㄷㄸㄹㅁㅂㅃㅅㅆㅇㅈㅉㅊㅋㅌㅍㅎ'
JUNG = 'ㅏㅐㅑㅒㅓㅔㅕㅖㅗㅘㅙㅚㅛㅜㅝㅞㅟㅠㅡㅢㅣ'
JONG = ' ㄱㄲㄳㄴㄵㄶㄷㄹㄺㄻㄼㄽㄾㄿㅀㅁㅂㅄㅅㅆㅇㅈㅊㅋㅌㅍㅎ'
JUNG_MIX = {('ㅗ', 'ㅏ'): 'ㅘ', ('ㅗ', 'ㅐ'): 'ㅙ', ('ㅗ', 'ㅣ'): 'ㅚ', ('ㅜ', 'ㅓ'): 'ㅝ',
            ('ㅜ', 'ㅔ'): 'ㅞ', ('ㅜ', 'ㅣ'): 'ㅟ', ('ㅡ', 'ㅣ'): 'ㅢ'}
JONG_MIX = {('ㄱ', 'ㅅ'): 'ㄳ', ('ㄴ', 'ㅈ'): 'ㄵ', ('ㄴ', 'ㅎ'): 'ㄶ', ('ㄹ', 'ㄱ'): 'ㄺ',
            ('ㄹ', 'ㅁ'): 'ㄻ', ('ㄹ', 'ㅂ'): 'ㄼ', ('ㄹ', 'ㅅ'): 'ㄽ', ('ㄹ', 'ㅌ'): 'ㄾ',
            ('ㄹ', 'ㅍ'): 'ㄿ', ('ㄹ', 'ㅎ'): 'ㅀ', ('ㅂ', 'ㅅ'): 'ㅄ'}
KS = sorted((bytes([hi, lo]).decode('euc-kr') for hi in range(0xB0, 0xC9) for lo in range(0xA1, 0xFF)), key=ord)
GLYPH_BYTES = 12
# Bank tails that are zero in the JP ROM and in v1.2 and that no screen read
# while playing through the test savestates (glyph data only needs to be read
# by the S-CPU, so any bank works).
GLYPH_RUNS = [(0x1A4DA0, 12896), (0x1C6506, 6906), (0x1DEBE0, 5153), (0x37B5E8, 10778)]
SYL_TABLE = 0x3AED44      # NeKsSyl, 4796 bytes free
DATA_BASE = 0x15EFEB      # NeKsStatic and the small tables, 4117 bytes free
DATA_FREE = 4117
SYL_FREE = 4796

# Grid: 8 rows x 11 columns, column 10 holds the commands. Cells hold a jamo,
# a menu-font character, or one of the commands; None is a gap the cursor skips.
SPACE, BACK, DONE = 'SPACE', 'BACK', 'DONE'
GRID = [
    list('ㄱㄴㄷㄹㅁㅂㅅㅇㅈㅊ') + [None],
    list('ㅋㅌㅍㅎㄲㄸㅃㅆㅉ') + [None, None],
    [None] * 11,
    list('ㅏㅑㅓㅕㅗㅛㅜㅠㅡㅣ') + [None],
    list('ㅐㅒㅔㅖㅘㅙㅚㅝㅞㅟ') + [None],
    ['ㅢ'] + [None] * 9 + [SPACE],
    list(range(0x30, 0x3A)) + [BACK],
    [0x3F, 0x24, 0x25, 0x40, 0x5B, 0x5D, 0x2C, 0x2B, 0x2F, None, DONE],
]
# Digits and symbols are menu-font codes checked against the glyphs (korTBL2's
# punctuation lines do not match them): 0-9, then ? ♥ ♪ ★ - . , : /
LABELS = {SPACE: '띄우기', BACK: '지우기', DONE: '완료'}
CMD_CODE = {SPACE: 0xFFF0, BACK: 0xFFF1, DONE: 0xFFF2}


def syl(cho, jung, jong=0):
    return chr(0xAC00 + (cho * 21 + jung) * 28 + jong)


def render(render_glyph, font, ch):
    """8x12 1bpp rows, from the same Galmuri rendering as the other glyphs."""
    return render_glyph(font, ch)[::2]


def code16(ch, tbl):
    if ch in tbl and tbl[ch] >= 0x20:
        return tbl[ch]
    if ch in JAMO:
        return 0x8000 | JAMO.index(ch)
    if ch in KS:
        return 0x8000 | (len(JAMO) + KS.index(ch))
    sys.exit(f'name entry: no glyph for {ch!r}')


def build(tbl, render_glyph, font, build_dir, trusted):
    """tbl: menu-font character -> code; trusted: codes whose glyph is known to be
    that character (data/tbl/menu_font_audit.txt and the codes build.py redraws).
    Writes name_entry_data.asm and the glyph chunks."""
    tbl = {ch: c for ch, c in tbl.items() if c in trusted and trusted[c] == ch}
    hangul_static = {ch: c for ch, c in tbl.items() if '가' <= ch <= '힣' and c >= 0x20}
    missing = sorted(set(hangul_static) - set(KS))
    if missing:
        sys.exit(f'menu-font syllables outside KS X 1001: {missing}')
    glyphs = [render(render_glyph, font, ch) for ch in JAMO + KS]
    asm = ['; generated by tools/build.py (tools/py/name_entry.py)']

    chunks, gi = [], 0
    for k, (start, size) in enumerate(GLYPH_RUNS):
        n = min(size // GLYPH_BYTES, len(glyphs) - gi)
        if n <= 0:
            continue
        name = f'name_glyphs{k}.bin'
        (build_dir / name).write_bytes(b''.join(glyphs[gi:gi + n]))
        snes = 0xC00000 | start
        asm += [f'org ${snes:06X}', f'NeGlyphs{len(chunks)}:', f'    incbin "{name}"',
                f'assert pc() <= ${snes + size:06X}']
        chunks.append((gi, snes))
        gi += n
    if gi < len(glyphs) or len(chunks) != 4:
        sys.exit(f'name glyph space: {len(glyphs)} glyphs, placed {gi} in {len(chunks)} runs')
    for k, (first, _) in enumerate(chunks):
        asm.append(f'!ne_chunk{k} = ${first:04X}')

    syls = [ord(ch) - 0xAC00 for ch in KS]
    asm += [f'org ${0xC00000 | SYL_TABLE:06X}', 'NeKsSyl:']
    asm += ['    dw ' + ','.join(f'${s:04X}' for s in syls[i:i + 16]) for i in range(0, len(syls), 16)]
    asm += [f'assert pc() <= ${0xC00000 | (SYL_TABLE + SYL_FREE):06X}', f'!ne_ks_count = {len(KS)}']

    def db(label, values):
        out = [f'{label}:']
        values = list(values)
        out += ['    db ' + ','.join(f'${v:02X}' for v in values[i:i + 16]) for i in range(0, len(values), 16)]
        return out

    asm += [f'org ${0xC00000 | DATA_BASE:06X}']
    asm += db('NeKsStatic', [hangul_static.get(ch, 0) for ch in KS])
    asm += db('NeJCho', [CHO.index(j) if j in CHO else 0xFF for j in JAMO])
    asm += db('NeJJung', [JUNG.index(j) if j in JUNG else 0xFF for j in JAMO])
    asm += db('NeJJong', [JONG.index(j) if j in JONG[1:] else 0 for j in JAMO])
    asm += db('NeChoJ', [JAMO.index(j) for j in CHO])
    asm += db('NeJungJ', [JAMO.index(j) for j in JUNG])
    # Splitting a final consonant when a vowel follows: what stays, and the
    # initial consonant that moves to the next syllable.
    rest, move = [0], [0xFF]
    for j in JONG[1:]:
        pair = next((k for k, v in JONG_MIX.items() if v == j), None)
        rest.append(JONG.index(pair[0]) if pair else 0)
        move.append(CHO.index(pair[1] if pair else j))
    asm += db('NeJongRest', rest) + db('NeJongMove', move)
    asm += db('NeJungMix', [x for (a, b), r in JUNG_MIX.items() for x in (JUNG.index(a), JAMO.index(b), JUNG.index(r))] + [0xFF])
    asm += db('NeJongMix', [x for (a, b), r in JONG_MIX.items() for x in (JONG.index(a), JAMO.index(b), JONG.index(r))] + [0xFF])

    cells = []
    for row in GRID:
        if len(row) != 11:
            sys.exit('name entry grid rows need 11 cells')
        for ch in row:
            cells.append(0 if ch is None else ch if isinstance(ch, int) else
                         CMD_CODE[ch] if ch in CMD_CODE else code16(ch, tbl))
    asm += ['NeGrid:'] + ['    dw ' + ','.join(f'${c:04X}' for c in cells[i:i + 11]) for i in range(0, len(cells), 11)]
    for cmd, text in LABELS.items():
        asm += [f'NeLabel{cmd.title()}:', '    dw ' + ','.join(f'${code16(ch, tbl):04X}' for ch in text) + ',$0000']
    asm.append(f'assert pc() <= ${0xC00000 | (DATA_BASE + DATA_FREE):06X}')
    (build_dir / 'name_entry_data.asm').write_text('\n'.join(asm) + '\n')
    return len(glyphs)

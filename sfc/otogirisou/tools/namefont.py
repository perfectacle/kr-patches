"""v1.3: glyphs for every name the jamo name entry can make, and the data asm/nameentry.asm reads.

The dialogue font keeps every existing code and bitmap. Codes from NEW_FIRST on get the
51 compatibility jamo and the KS X 1001 syllables the font lacks, drawn with Galmuri11 like
the v1.1 fallback glyphs. They form one 11x11 group whose data lives in bank $36; the
decoder hook in asm/nameentry.asm picks that bank for groups from NEW_GROUP on.

Writes into the ROM: the new group entry, the glyph data, the widths of the new codes.
Writes build/name_defs.asm (constants), build/name_data.asm (syllable lookup, jamo tables, the jamo page of the name entry
screen) and build/kr13.tbl (build/kr.tbl plus the new codes).

usage: namefont.py rom.sfc kr.tbl
"""
import os
import sys

sys.path.insert(0, os.path.dirname(__file__))
from font import groups, GROUPS  # noqa: E402
from mkfont import TABLE_END, WIDTHS, hangul_box, hangul_glyph, is_hangul, pack, render  # noqa: E402

ROOT = os.path.join(os.path.dirname(__file__), '..')
NEW_FIRST = 1689
NEW_GROUP = 48
DATA_BANK = 0x36
DATA_OFF = DATA_BANK * 0x8000          # file offset of $36:8000
DATA_END = DATA_OFF + 0x5000           # glyphs; the code and tables follow from $36:D000
JAMO = [chr(c) for c in range(0x3131, 0x3164)]
CHO = 'ㄱㄲㄴㄷㄸㄹㅁㅂㅃㅅㅆㅇㅈㅉㅊㅋㅌㅍㅎ'
JUNG = 'ㅏㅐㅑㅒㅓㅔㅕㅖㅗㅘㅙㅚㅛㅜㅝㅞㅟㅠㅡㅢㅣ'
JONG = ' ㄱㄲㄳㄴㄵㄶㄷㄹㄺㄻㄼㄽㄾㄿㅀㅁㅂㅄㅅㅆㅇㅈㅊㅋㅌㅍㅎ'
JUNG_MIX = {('ㅗ', 'ㅏ'): 'ㅘ', ('ㅗ', 'ㅐ'): 'ㅙ', ('ㅗ', 'ㅣ'): 'ㅚ', ('ㅜ', 'ㅓ'): 'ㅝ',
            ('ㅜ', 'ㅔ'): 'ㅞ', ('ㅜ', 'ㅣ'): 'ㅟ', ('ㅡ', 'ㅣ'): 'ㅢ'}
JONG_MIX = {('ㄱ', 'ㅅ'): 'ㄳ', ('ㄴ', 'ㅈ'): 'ㄵ', ('ㄴ', 'ㅎ'): 'ㄶ', ('ㄹ', 'ㄱ'): 'ㄺ',
            ('ㄹ', 'ㅁ'): 'ㄻ', ('ㄹ', 'ㅂ'): 'ㄼ', ('ㄹ', 'ㅅ'): 'ㄽ', ('ㄹ', 'ㅌ'): 'ㄾ',
            ('ㄹ', 'ㅍ'): 'ㄿ', ('ㄹ', 'ㅎ'): 'ㅀ', ('ㅂ', 'ㅅ'): 'ㅄ'}
KS = sorted((bytes([hi, lo]).decode('euc-kr') for hi in range(0xB0, 0xC9) for lo in range(0xA1, 0xFF)), key=ord)
# Hangul page 1 of the name entry screen ($02:AAB4, 5 columns x 10 rows, 0 = empty cell):
# the 2-set keyboard split into its consonant half and its vowel half, Shift row on top of each.
JAMO_PAGE = [
    'ㅃㅉㄸㄲㅆ', 'ㅂㅈㄷㄱㅅ', 'ㅁㄴㅇㄹㅎ', 'ㅋㅌㅊㅍ ', '     ',
    '   ㅒㅖ', 'ㅛㅕㅑㅐㅔ', 'ㅗㅓㅏㅣ ', 'ㅠㅜㅡ  ', '     ',
]
PAGE1 = 0x12AB4                        # $02:AAB4, 50 codes and $FFFF


def jamo_glyph(ch, top):
    g = render(ch)[top:top + 11]
    assert not any(any(r[11:]) for r in render(ch)), ch
    return [r[:11] for r in g]


def main(romp, tblp):
    rom = bytearray(open(romp, 'rb').read())
    table = {}
    for line in open(tblp, encoding='utf-8'):
        code, _, ch = line.rstrip('\n').partition('\t')
        if code.isdigit():
            table[int(code)] = ch
    gs = groups(rom)
    if len(gs) != NEW_GROUP or gs[-1][0] + gs[-1][1] != NEW_FIRST:
        raise SystemExit('unexpected font: %d groups ending at %d' % (len(gs), gs[-1][0] + gs[-1][1]))
    have = {ch: code for code, ch in sorted(table.items(), reverse=True) if is_hangul(ch)}
    top = hangul_box()
    new = JAMO + [ch for ch in KS if ch not in have]
    codes = {ch: NEW_FIRST + i for i, ch in enumerate(new)}
    glyphs = [jamo_glyph(ch, top) if ch in JAMO else hangul_glyph(ch, top) for ch in new]

    data = pack(glyphs)
    if DATA_OFF + len(data) + 2 > DATA_END:
        raise SystemExit('name glyphs overflow bank $36')
    if any(rom[DATA_OFF:DATA_END + 0x3000]):
        raise SystemExit('bank $36 is not empty')
    rom[DATA_OFF:DATA_OFF + len(data)] = data
    e = GROUPS + 5 * NEW_GROUP
    cnt = len(new)
    if e + 10 > TABLE_END or any(rom[e:e + 5]):
        raise SystemExit('group table slot %d is not free' % NEW_GROUP)
    rom[e:e + 5] = bytes([cnt & 0xFF, (cnt >> 8) | (11 << 4), 0x00, 0x80, 11 << 2])
    for code in codes.values():
        rom[WIDTHS + code] = 11

    page = []
    for row in JAMO_PAGE:
        page += [codes[ch] if ch != ' ' else 0 for ch in row.ljust(5)]
    assert len(page) == 50
    rom[PAGE1:PAGE1 + 102] = b''.join(c.to_bytes(2, 'little') for c in page) + b'\xff\xff'
    open(romp, 'wb').write(rom)

    def db(label, values):
        values = list(values)
        return [f'{label}:'] + ['    db ' + ','.join(f'${v:02X}' for v in values[i:i + 16])
                                for i in range(0, len(values), 16)]

    def dw(label, values):
        values = list(values)
        return [f'{label}:'] + ['    dw ' + ','.join(f'${v:04X}' for v in values[i:i + 16])
                                for i in range(0, len(values), 16)]

    rest, move = [0], [0xFF]
    for j in JONG[1:]:
        pair = next((k for k, v in JONG_MIX.items() if v == j), None)
        rest.append(JONG.index(pair[0]) if pair else 0)
        move.append(CHO.index(pair[1] if pair else j))
    defs = ['; generated by tools/namefont.py', f'!ne_jamo_first = {NEW_FIRST}', f'!ne_ks_count = {len(KS)}',
            f'!ne_new_group = {NEW_GROUP}', f'!ne_font_bank = ${DATA_BANK:02X}']
    asm = ['; generated by tools/namefont.py']
    asm += dw('NeKsSyl', (ord(ch) - 0xAC00 for ch in KS))
    asm += dw('NeKsCode', (have.get(ch, codes.get(ch, 0)) for ch in KS))
    asm += db('NeJCho', (CHO.index(j) if j in CHO else 0xFF for j in JAMO))
    asm += db('NeJJung', (JUNG.index(j) if j in JUNG else 0xFF for j in JAMO))
    asm += db('NeJJong', (JONG.index(j) if j in JONG[1:] else 0 for j in JAMO))
    asm += db('NeChoJ', (JAMO.index(j) for j in CHO))
    asm += db('NeJungJ', (JAMO.index(j) for j in JUNG))
    asm += db('NeJongRest', rest) + db('NeJongMove', move)
    asm += db('NeJungMix', [x for (a, b), r in JUNG_MIX.items() for x in (JUNG.index(a), JAMO.index(b), JUNG.index(r))] + [0xFF])
    asm += db('NeJongMix', [x for (a, b), r in JONG_MIX.items() for x in (JONG.index(a), JAMO.index(b), JONG.index(r))] + [0xFF])
    out = os.path.join(ROOT, 'build')
    open(os.path.join(out, 'name_defs.asm'), 'w').write('\n'.join(defs) + '\n')
    open(os.path.join(out, 'name_data.asm'), 'w').write('\n'.join(asm) + '\n')
    with open(os.path.join(out, 'kr13.tbl'), 'w', encoding='utf-8') as f:
        for code, ch in sorted({**table, **{c: ch for ch, c in codes.items()}}.items()):
            f.write('%d\t%s\n' % (code, ch))
    print('name glyphs %d (jamo %d, syllables %d), codes %d-%d, %d bytes in bank $%02X'
          % (cnt, len(JAMO), cnt - len(JAMO), NEW_FIRST, NEW_FIRST + cnt - 1, len(data), DATA_BANK))


if __name__ == '__main__':
    main(*sys.argv[1:])
